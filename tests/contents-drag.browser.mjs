import assert from 'node:assert/strict';
import { mkdir, mkdtemp, realpath } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createServer } from 'vite';
await mkdir('output/playwright/contents-drag', { recursive: true });
const output = await mkdtemp('output/playwright/contents-drag/run-');
const server = await createServer({ cacheDir: `${output}/vite-cache`, server: { host:'127.0.0.1', port:0, hmr:false, watch:null, fs:{allow:[process.cwd(),await realpath('node_modules')]} }, clearScreen:false });
let browser;
try {
  await server.listen();
  browser = await chromium.launch(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : { channel: 'chrome' });
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`);
  await page.locator('#book-spread[aria-busy="false"] > .paper-page').first().waitFor();
  const panel=page.locator('#book-contents'), handle=page.locator('.contents-drag-handle');
  const bookBefore=await page.locator('#book-spread').boundingBox();
  const before=await panel.boundingBox();
  await handle.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(Math.round((await panel.boundingBox()).x-before.x),20);
  assert.deepEqual(await page.locator('#book-spread').boundingBox(),bookBefore);
  await page.keyboard.press('Home');
  assert.equal(Math.round((await panel.boundingBox()).x),Math.round(before.x));
  const h=await handle.boundingBox();
  await page.mouse.move(h.x+h.width/2,h.y+h.height/2); await page.mouse.down();
  await page.mouse.move(h.x+400,h.y+h.height/2); await page.mouse.up();
  assert.ok((await panel.boundingBox()).x>before.x+300);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#contents-toggle').click(); await page.waitForTimeout(400);
  let box=await panel.boundingBox(); assert.ok(box.x>=-1 && box.x+box.width<=391);
  await page.locator('#contents-close').click(); await page.waitForTimeout(400);
  assert.equal(await panel.isVisible(),false);
  await page.locator('#contents-toggle').click(); await page.waitForTimeout(400);
  await handle.focus(); await page.keyboard.press('Home');
  box=await panel.boundingBox(); assert.ok(Math.abs(box.x)<1);
  await page.screenshot({path:`${output}/contents-mobile.png`});
  assert.deepEqual(errors,[]);
  console.log('PASS contents horizontal placement: keyboard, pointer, fixed reader, mobile clamp and drawer.');
} finally {await browser?.close();await server.close();}
