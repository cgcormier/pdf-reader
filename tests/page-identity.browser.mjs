import assert from 'node:assert/strict';
import { mkdir, mkdtemp } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { makeLayoutPdf } from './pdf-layout-fixture.mjs';
import { settledReader } from './reader-capture.mjs';
await mkdir('output/playwright', { recursive: true });
const run = await mkdtemp('output/playwright/page-identity-');
const server = await createServer({cacheDir:`${run}/cache`, server:{host:'127.0.0.1',port:0,hmr:false,watch:null}});
let browser;
try {
  await server.listen();
  browser = await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE || '/usr/bin/chromium',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await page.goto(server.resolvedUrls.local[0]);
  await settledReader(page,1);
  assert.match(await page.locator('#page-position-label').textContent(), /^Source pages?$/);
  assert.equal(await page.locator('#page-input').getAttribute('aria-label'),'Go to source page');
  assert.match(await page.locator('.page-number').first().getAttribute('aria-label'),/^Source page 1/);
  assert.doesNotMatch(await page.locator('#total-pages').textContent(),/continued/);
  await page.locator('#page-input').fill('3'); await page.locator('#page-input').press('Enter'); await settledReader(page,3);
  const before = await page.locator('#page-input').inputValue();
  await page.locator('#appearance-button').focus(); await page.keyboard.press('ArrowRight'); await settledReader(page,3);
  assert.equal(await page.locator('#page-input').inputValue(), before);
  await page.locator('#scroll-layout').click(); await settledReader(page,3);
  assert.equal(await page.locator('#page-position-label').textContent(),'Source page');
  const pages = Array.from({length:3}, (_, i) => ({items:Array.from({length:28},(_,j)=>({text:`Source ${i+1}, line ${j+1}. This is a deliberately long imported paragraph for a stable source page identity test.`,x:40,y:740-j*20,size:10}))}));
  await page.locator('#file-input').setInputFiles({name:'source-identity.pdf',mimeType:'application/pdf',buffer:Buffer.from(makeLayoutPdf(pages))});
  await page.waitForFunction(()=>!document.querySelector('#modal').open && document.querySelector('#book-type').textContent==='FROM YOUR SHELF');
  await settledReader(page,1);
  assert.equal(await page.locator('#total-pages').textContent(),'of 3');
  await page.locator('#pages-layout').click(); await settledReader(page,1);
  const leaves = await page.locator('#book-spread > .paper-page:not(.end-page)').evaluateAll(nodes=>nodes.map(n=>({page:n.dataset.sourcePage,offset:Number(n.dataset.textOffset),label:n.getAttribute('aria-label')})));
  assert.ok(leaves.every(n=>n.label===`Source page ${n.page}${n.offset?', continued':''}`));
  await page.locator('#page-input').fill('2'); await page.locator('#page-input').press('Enter'); await settledReader(page,2);
  assert.equal(await page.locator('#page-input').inputValue(),'2');
  await page.screenshot({path:`${run}/imported.png`});
  console.log('PASS sample, resize/text-size identity, scroll, imported PDF, continued leaves and source navigation');
  console.log(run);
} finally { await browser?.close(); await server.close(); }
